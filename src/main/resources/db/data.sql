-- 活动状态分布（成团率统计 #23 的基础数据）
SELECT status,
       CASE status WHEN 0 THEN '待开始' WHEN 1 THEN '进行中' WHEN 2 THEN '已成团'
                   WHEN 3 THEN '已失败' WHEN 4 THEN '已下架' END AS status_name,
       COUNT(*) AS cnt, SUM(current_num) AS joined, SUM(target_num) AS target
FROM activity GROUP BY status ORDER BY status;

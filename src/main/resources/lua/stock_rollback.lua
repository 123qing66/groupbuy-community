-- ============================================================
-- 库存回滚：支付失败 / 订单取消 / 拼团失败退款时调用
-- KEYS[1] = 库存 key
-- ARGV[1] = 要回滚的数量
-- 返回: 1=成功  0=key不存在
-- ============================================================
if redis.call('EXISTS', KEYS[1]) == 0 then
    return 0
end

redis.call('INCRBY', KEYS[1], ARGV[1])
return 1

-- ============================================================
-- 释放锁：只能释放自己加的锁（比对 value），避免误删别人的锁
-- KEYS[1] = 锁 key
-- ARGV[1] = 加锁时写入的唯一 value
-- 返回: 1=释放成功  0=锁不属于自己或已过期
-- ============================================================
if redis.call('GET', KEYS[1]) == ARGV[1] then
    return redis.call('DEL', KEYS[1])
end
return 0
